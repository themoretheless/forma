from decimal import Decimal, localcontext
from pathlib import Path
import math, struct


def d(v):
    bits = struct.unpack('<Q', struct.pack('<d', float(v)))[0]
    return f'D64(0x{bits & 0xffffffff:08x}u, 0x{bits >> 32:08x}u)'


def select_tree(items, lo=0, hi=None):
    if hi is None:
        hi = len(items)
    if hi - lo == 1:
        return items[lo]
    mid = (lo + hi) // 2
    return f'select({select_tree(items, lo, mid)}, {select_tree(items, mid, hi)}, index >= {mid}u)'


with localcontext() as ctx:
    ctx.prec = 460

    def atan(x):
        x = Decimal(x)
        term = x
        total = x
        k = 1
        while abs(term) > Decimal('1e-455'):
            term *= -x * x
            total += term / Decimal(2 * k + 1)
            k += 1
        return total

    pi = 16 * atan(Decimal(1) / 5) - 4 * atan(Decimal(1) / 239)
    fixed = int(2 / pi * Decimal(2) ** 1280)
    words = [(fixed >> (32 * i)) & 0xffffffff for i in range(40)]
    ln2 = Decimal(2).ln()
    high = struct.unpack('<d', struct.pack('<Q', 0x3fe62e42fee00000))[0]
    consts = '\n'.join(
        f'const {name}: D64 = {d(value)};'
        for name, value in [
            ('D64_HALF', 0.5),
            ('D64_TWO', 2),
            ('D64_LN2', ln2),
            ('D64_LN2_HI', high),
            ('D64_LN2_LO', ln2 - Decimal(high)),
            ('D64_PIO2', pi / 2),
            ('D64_PIO2_LO', pi / 2 - Decimal(float(pi / 2))),
            ('D64_SQRT2', Decimal(2).sqrt()),
        ]
    )

    def poly(name, coeffs):
        rev = list(reversed(coeffs[:-1]))
        exprs = [d(c) for c in rev]
        return (
            f'fn {name}_coeff(index: u32) -> D64 {{\n'
            f'    return {select_tree(exprs)};\n'
            f'}}\n'
            f'fn {name}(x: D64) -> D64 {{\n'
            f'    var value = {d(coeffs[-1])};\n'
            f'    for (var i = 0u; i < {len(rev)}u; i += 1u) {{\n'
            f'        value = d64_add({name}_coeff(i), d64_mul(x, value));\n'
            f'    }}\n'
            f'    return value;\n'
            f'}}\n'
        )

    word_exprs = [f'0x{w:08x}u' for w in words]
    two_over_pi = (
        'fn d64_two_over_pi_word(index: u32) -> u32 {\n'
        f'    return select(0u, {select_tree(word_exprs)}, index < {len(words)}u);\n'
        '}\n'
    )
    sections = [
        '// Constants generated by tools/generate-binary64-constants.py; integer words only.',
        '// --- CONSTS ---',
        consts,
        '// --- EXP ---',
        poly('d64_exp_poly', [Decimal(1) / math.factorial(i) for i in range(21)]).rstrip('\n'),
        '// --- LOG ---',
        poly('d64_log_poly', [Decimal(1) / Decimal(2 * i + 1) for i in range(14)]).rstrip('\n'),
        '// --- SINCOS ---',
        two_over_pi
        + poly('d64_sin_poly', [Decimal((-1) ** i) / math.factorial(2 * i + 1) for i in range(10)])
        + poly('d64_cos_poly', [Decimal((-1) ** i) / math.factorial(2 * i) for i in range(11)]).rstrip('\n'),
    ]

(Path(__file__).resolve().parents[1] / 'src/binary64/constants.wgsl').write_text('\n'.join(sections) + '\n')
