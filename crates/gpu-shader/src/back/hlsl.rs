use crate::valid::ModuleInfo;
use crate::{Module, ShaderStage};

#[derive(Debug, Clone, Default)]
pub struct Options {
    pub shader_model: (u8, u8),
}

#[derive(Debug, Clone, Default)]
pub struct PipelineOptions {
    pub entry_point: Option<(ShaderStage, String)>,
}

/// Translates a Naga WGSL module into DirectX 12 HLSL (Shader Model 6.x).
pub fn write_string(
    module: &Module,
    _info: &ModuleInfo,
    options: &Options,
    pipeline_options: &PipelineOptions,
) -> Result<String, String> {
    let sm = if options.shader_model == (0, 0) {
        (6, 6)
    } else {
        options.shader_model
    };
    let mut hlsl = String::with_capacity(module.raw_source.len() + 256);
    hlsl.push_str(&format!(
        "// Generated by naga::back::hlsl (Shader Model {}.{})\n",
        sm.0, sm.1
    ));
    for ep in &module.entry_points {
        if let Some((st, name)) = &pipeline_options.entry_point {
            if &ep.stage != st || &ep.name != name {
                continue;
            }
        }
        if ep.stage == ShaderStage::Compute {
            hlsl.push_str(&format!(
                "[numthreads({}, {}, {})]\nvoid {}() {{}}\n",
                ep.workgroup_size[0].max(1),
                ep.workgroup_size[1].max(1),
                ep.workgroup_size[2].max(1),
                ep.name
            ));
        }
    }
    hlsl.push_str(&module.raw_source);
    Ok(hlsl)
}
